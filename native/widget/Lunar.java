    private static final String[] MONTH = {"", "正月", "二月", "三月", "四月", "五月", "六月", "七月", "八月", "九月", "十月", "冬月", "臘月"};

    private Lunar() {}

    /** 傳入距 1970/01/01 的天數，回傳格子裡要顯示的農曆（初一顯示月份）；超出範圍回傳空字串 */
    static String label(long epochDay) {
        int i = -1;
        for (int k = 0; k < NEW_YEAR.length - 1; k++) if (epochDay >= NEW_YEAR[k] && epochDay < NEW_YEAR[k + 1]) { i = k; break; }
        if (i < 0) return "";
        long off = epochDay - NEW_YEAR[i];
        for (String tok : MONTHS[i].split(" ")) {
            boolean leap = tok.contains("L");
            int len = Integer.parseInt(tok.substring(tok.length() - 2));
            int m = Integer.parseInt(tok.substring(0, tok.length() - 2 - (leap ? 1 : 0)));
            if (off < len) {
                int day = (int) off + 1;
                return day == 1 ? (leap ? "閏" : "") + MONTH[m] : DAY[day];
            }
            off -= len;
        }
        return "";
    }
